#!/usr/bin/env python3
"""Write src/pocketpy.cppm from pocketpy.h.

src/pocketpy.cppm exports every type, enumerator and function of the public
header <pocketpy.h> (pocketpy/pocketpy.h with config.h, export.h and vmath.h)
by `export using`: the upstream globals, unchanged. pocketpy.h has no
`static inline` function, so nothing needs adapting.

py_callcfunc is a function only without NDEBUG (a macro calling the function
directly with it); it is the macros module's, as one function for both.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

HEADER = '''// Generated by tools/gen_exports.py from pocketpy.h (PocketPy 2.2.0) — do not
// edit by hand.
//
// mcpplibs.mwrap.pocketpy — PocketPy, the embeddable Python interpreter, as a
// C++ module. Every exported name is the upstream global of <pocketpy.h>,
// unchanged; the root also re-exports the macro mappings. The interpreter is
// compat.pocketpy, built from the same release.
//
// py_callcfunc is declared by the header only without NDEBUG; it is in
// mcpplibs::mwrap::pocketpy::macros, one function for both.
module;
#include <pocketpy.h>

export module mcpplibs.mwrap.pocketpy;

export import mcpplibs.mwrap.pocketpy.macros;
'''


def render(sf):
    out = [HEADER]
    out.append(f'// types ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// enumerators ({len(sf.enumerators)})')
    out += [f'export using ::{n};' for n in sf.enumerators]
    out.append(f'\n// functions ({len(sf.functions)})')
    out += [f'export using ::{n};' for n in sf.functions]
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    text = render(surface(fetch(root)))
    path = root / 'src/pocketpy.cppm'
    current = path.read_text(encoding='utf-8') if path.exists() else None
    if current == text:
        return
    if args.check:
        sys.exit('not what tools/gen_exports.py writes: src/pocketpy.cppm')
    path.write_text(text, encoding='utf-8', newline='\n')
    print('wrote src/pocketpy.cppm')


if __name__ == '__main__':
    main()
